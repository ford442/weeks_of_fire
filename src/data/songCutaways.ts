import type { CutawaySegment, CutawaySuggestion } from './suggestions';

function mv(
  id: string,
  title: string,
  songId: string,
  songTitle: string,
  episode: string,
  runtime: string,
  summary: string,
  visualArc: string,
  tags: string[],
  segments: CutawaySegment[],
): CutawaySuggestion {
  return {
    id,
    kind: 'musical',
    title,
    status: 'ready-to-generate',
    runtime,
    episode,
    songId,
    songTitle,
    summary,
    visualArc,
    tags,
    segments,
  };
}

function beat(
  id: string,
  label: string,
  start: string,
  end: string,
  durationSec: number,
  onScreen: string,
  lyrics: string,
  musicCue: string,
  grokImaginePrompt: string,
  geminiOmniPrompt: string,
  promptVariations: string[] = [],
): CutawaySegment {
  return {
    id,
    label,
    start,
    end,
    durationSec,
    onScreen,
    lyrics,
    musicCue,
    grokImaginePrompt,
    geminiOmniPrompt,
    promptVariations,
  };
}

