import type { CutawaySegment, CutawaySuggestion } from './suggestions';

function mv(
  id: string,
  title: string,
  songId: string,
  songTitle: string,
  episode: string,
  runtime: string,
  summary: string,
  visualArc: string,
  tags: string[],
  segments: CutawaySegment[],
): CutawaySuggestion {
  return {
    id,
    kind: 'musical',
    title,
    status: 'ready-to-generate',
    runtime,
    episode,
    songId,
    songTitle,
    summary,
    visualArc,
    tags,
    segments,
  };
}

